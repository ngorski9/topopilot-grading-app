from paraview.simple import *
from paraview import servermanager
from vtk.util.numpy_support import vtk_to_numpy
import numpy as np

DATA = '/workspace/QMCPACK.vti'
STATE = '/workspace/QMCPACK_topology_visualization.pvsm'
IMAGE = '/workspace/QMCPACK_topology_visualization.png'
SCALAR = 'Scalars_'

reader = XMLImageDataReader(registrationName='QMCPACK volume', FileName=[DATA])
reader.PointArrayStatus = [SCALAR]

# TTK's persistence-aware simplifier cancels all pairs below 0.04.
simplified = TTKTopologicalSimplificationByPersistence(
    registrationName='Persistence simplification (0.04)', Input=reader)
simplified.InputArray = ['POINTS', SCALAR]
simplified.PersistenceThreshold = 0.04
simplified.ThresholdIsAbsolute = 1
UpdatePipeline(proxy=simplified)

# Discover the scalar array retained/generated by the simplification filter.
out = servermanager.Fetch(simplified)
point_data = out.GetPointData()
scalar_name = SCALAR if point_data.GetArray(SCALAR) else point_data.GetArray(0).GetName()
values = vtk_to_numpy(point_data.GetArray(scalar_name))
levels = [float(np.quantile(values, q)) for q in (0.2, 0.4, 0.6, 0.8)]
print('Simplified scalar:', scalar_name)
print('Equal-volume isovalues:', ', '.join(f'{x:.8g}' for x in levels))

contours = Contour(registrationName='4 equal-volume isocontours', Input=simplified)
contours.ContourBy = ['POINTS', scalar_name]
contours.Isosurfaces = levels
contours.PointMergeMethod = 'Uniform Binning'

critical = TTKScalarFieldCriticalPoints(
    registrationName='All PL critical points', Input=simplified)
critical.ScalarField = ['POINTS', scalar_name]
critical.ForceInputOffsetField = 0
critical.Withvertexscalars = 1
UpdatePipeline(proxy=critical)

# Separate each PL critical type so its requested color remains unambiguous.
types = [
    ('Minima (blue)', 0, (0.10, 0.30, 1.00)),
    ('1-saddles (white)', 1, (1.00, 1.00, 1.00)),
    ('2-saddles (orange)', 2, (1.00, 0.45, 0.00)),
    ('Maxima (red)', 3, (1.00, 0.05, 0.05)),
    # TTK reports degenerate multi-saddles separately; retain them as well.
    ('Multi-saddles (purple)', 4, (0.78, 0.20, 0.95)),
]

view = CreateView('RenderView')
view.ViewSize = [1600, 1000]
view.Background = [0.055, 0.055, 0.075]
view.BackgroundColorMode = 'Gradient'
view.Background2 = [0.16, 0.16, 0.21]

contour_display = Show(contours, view)
contour_display.Representation = 'Surface'
contour_display.DiffuseColor = [0.40, 0.72, 0.86]
contour_display.Opacity = 0.34
contour_display.Specular = 0.35
contour_display.SpecularPower = 25.0

for label, critical_type, color in types:
    selection = Threshold(registrationName=label, Input=critical)
    selection.Scalars = ['POINTS', 'CriticalType']
    selection.LowerThreshold = critical_type
    selection.UpperThreshold = critical_type
    selection.ThresholdMethod = 'Between'
    display = Show(selection, view)
    display.Representation = 'Points'
    display.DiffuseColor = color
    display.PointSize = 13.0
    display.RenderPointsAsSpheres = 1

outline = Outline(registrationName='Volume bounds', Input=simplified)
outline_display = Show(outline, view)
outline_display.DiffuseColor = [0.72, 0.72, 0.77]
outline_display.LineWidth = 1.3

view.ResetCamera()
view.CameraPosition = [183, -174, 164]
view.CameraFocalPoint = [34, 34, 57]
view.CameraViewUp = [0.05, 0.49, 0.87]
view.CameraParallelScale = 90
Render(view)
SaveScreenshot(IMAGE, view, ImageResolution=[1600, 1000])
SaveState(STATE)
print('Saved:', STATE)
print('Saved:', IMAGE)
